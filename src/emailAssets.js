/**
 * Server-side helpers for what goes *inside* an e-mail:
 *
 *  - fetchImage(): downloads a company logo (Supabase Storage public URL,
 *    or a sector demo logo on dealz.website) so it can be embedded.
 *  - inlineImages(): rewrites <img src="https://..."> in an e-mail's HTML to
 *    cid: references with the image attached inline. Mail clients such as
 *    Infomaniak, Outlook or Apple Mail block remote images from unknown
 *    senders ("certain contents have been blocked") and show the alt text
 *    in a broken-image box instead of the logo. An inline (cid) image is
 *    part of the message itself, so it is shown right away. An image that
 *    cannot be downloaded is removed rather than left broken.
 *  - buildQuotePdf(): the same devis PDF the quote widget lets the customer
 *    download (docs/pdf-generator.js, jsPDF), built in Node so it can be
 *    attached to the booking confirmation e-mail.
 */
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const crypto = require("crypto");

const MAX_IMAGE_BYTES = 2 * 1024 * 1024;
const cache = new Map(); // url -> { at, value }
const CACHE_MS = 10 * 60 * 1000;

async function fetchImage(url) {
  if (!url || !/^https?:\/\//i.test(url)) return null;
  const hit = cache.get(url);
  if (hit && Date.now() - hit.at < CACHE_MS) return hit.value;
  let value = null;
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(6000) });
    const type = (res.headers.get("content-type") || "").split(";")[0].trim().toLowerCase();
    if (res.ok && type.startsWith("image/")) {
      const buffer = Buffer.from(await res.arrayBuffer());
      if (buffer.length && buffer.length <= MAX_IMAGE_BYTES) value = { buffer, type };
    } else {
      console.error(`[email image] ${url} -> HTTP ${res.status} ${type}`);
    }
  } catch (err) {
    console.error(`[email image] ${url} failed:`, err.message);
  }
  cache.set(url, { at: Date.now(), value });
  return value;
}

const EXT = { "image/png": "png", "image/jpeg": "jpg", "image/webp": "webp", "image/gif": "gif", "image/svg+xml": "svg" };

// Returns { html, attachments } with every remote <img> turned into an
// inline attachment (or dropped when it can't be downloaded).
async function inlineImages(html) {
  const urls = [...new Set([...String(html).matchAll(/<img\b[^>]*\bsrc="(https?:\/\/[^"]+)"/gi)].map((m) => m[1]))];
  if (!urls.length) return { html, attachments: [] };
  const attachments = [];
  let out = html;
  for (const raw of urls) {
    // The src went through escapeHtml in signatureHtml.
    const url = raw.replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&#39;/g, "'");
    const img = await fetchImage(url);
    if (img) {
      const cid = `img-${crypto.createHash("sha1").update(url).digest("hex").slice(0, 16)}@dealz.website`;
      attachments.push({ filename: `logo.${EXT[img.type] || "png"}`, content: img.buffer, contentType: img.type, cid, contentDisposition: "inline" });
      out = out.split(`src="${raw}"`).join(`src="cid:${cid}"`);
    } else {
      // Broken link: no image at all is better than a broken-image box.
      out = out.replace(new RegExp(`<img\\b[^>]*\\bsrc="${raw.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}"[^>]*>`, "gi"), "");
    }
  }
  return { html: out, attachments };
}

// ---- Quote PDF ----
let generator = null;
function loadGenerator() {
  if (generator) return generator;
  const window = { jspdf: require("jspdf") };
  const code = fs.readFileSync(path.join(__dirname, "..", "docs", "pdf-generator.js"), "utf8");
  vm.runInNewContext(code, { window, console, Date, Math, Number, String, Object, Array, JSON }, { filename: "pdf-generator.js" });
  generator = window.DealzPDF;
  return generator;
}

function pngSize(buffer) {
  // PNG signature + IHDR: width and height are at bytes 16..23.
  if (buffer.length < 24 || buffer.readUInt32BE(0) !== 0x89504e47) return null;
  return { w: buffer.readUInt32BE(16), h: buffer.readUInt32BE(20) };
}

const GENERATED = {
  fr: (n) => `Document généré automatiquement par Dealz pour ${n}.`,
  en: (n) => `Automatically generated by Dealz for ${n}.`,
  de: (n) => `Automatisch von Dealz für ${n} erstellt.`,
};
const FILE = { fr: "Devis", en: "Quote", de: "Offerte" };

// Returns a nodemailer attachment, or null when the PDF can't be built
// (it must never block the confirmation e-mail itself).
async function buildQuotePdf({ quote, customer, lang = "fr", company = {} }) {
  try {
    if (!quote || !Array.isArray(quote.items)) return null;
    const pdfCompany = { name: company.name || "Dealz", address: company.address || "", phone: company.phone || "", email: company.email || "" };
    const img = company.logoUrl ? await fetchImage(company.logoUrl) : null;
    const size = img && img.type === "image/png" ? pngSize(img.buffer) : null;
    if (size) pdfCompany.logo = { data: `data:image/png;base64,${img.buffer.toString("base64")}`, w: size.w, h: size.h };
    const { doc } = loadGenerator().generate(quote, customer || {}, lang, {
      company: pdfCompany,
      generated: (GENERATED[lang] || GENERATED.fr)(pdfCompany.name),
    });
    const content = Buffer.from(doc.output("arraybuffer"));
    const safeName = String(pdfCompany.name).normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "") || "Dealz";
    return { filename: `${FILE[lang] || FILE.fr}-${safeName}.pdf`, content, contentType: "application/pdf" };
  } catch (err) {
    console.error("[quote pdf] failed:", err.message);
    return null;
  }
}

module.exports = { fetchImage, inlineImages, buildQuotePdf };
